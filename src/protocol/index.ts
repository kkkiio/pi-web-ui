/**
 * Shared protocol types for pi-web-ui hub architecture (ADR 0012).
 *
 * Three parties share these shapes:
 * - extension (extensions/pi-web-ui.ts) — WebSocket client, one per Pi process
 * - hub (src/hub/) — standalone WebSocket + static server
 * - browser frontend (src/web/) — WebSocket client, attaches to one agent
 *
 * The req/res/event envelope is the same on both hops (browser ↔ hub and
 * hub ↔ extension). The hub rewrites request ids when relaying, so id
 * namespaces of different browsers never collide.
 */

export const PROTOCOL_VERSION = 1;

// ═══════════════════════════════════════
// Envelope (both hops)
// ═══════════════════════════════════════

export type WsRequest = {
  type: "req";
  id: string;
  method: string;
  params?: Record<string, unknown>;
};

export type WsResponse = {
  type: "res";
  id: string;
  ok: boolean;
  result?: unknown;
  error?: string;
};

export type WsEvent = {
  type: "event";
  event: string;
  payload: Record<string, unknown>;
};

export type WsError = {
  type: "error";
  id?: string;
  code: string;
  message: string;
};

// ═══════════════════════════════════════
// Agent identity
// ═══════════════════════════════════════

/**
 * agentId is stable for the lifetime of one Pi process (generated by the
 * extension, survives hub reconnects). sessionId derives from the session
 * file and changes on /new, fork, and session switch — the hub updates the
 * registry entry in place so attached browsers keep their view (ADR 0012).
 */
export type AgentSessionInfo = {
  agentId: string;
  sessionId: string | null;
  sessionName: string | null;
  sessionFile: string | null;
  cwd: string;
  pid: number;
  isStreaming: boolean;
};

// ═══════════════════════════════════════
// Extension → hub messages
// ═══════════════════════════════════════

export type AgentHello = {
  type: "hello";
  protocolVersion: number;
  agent: AgentSessionInfo;
};

/** Sent after session replacement (session_start) on the same connection. */
export type AgentSessionUpdate = {
  type: "session_update";
  agent: AgentSessionInfo;
};

export type ExtensionMessage = AgentHello | AgentSessionUpdate | WsResponse | WsEvent;

// ═══════════════════════════════════════
// Hub-level methods (browser → hub, never relayed)
// ═══════════════════════════════════════

/** List live agents. */
export const HUB_METHOD_LIST_SESSIONS = "list_sessions";
/** List recent sessions from ~/.pi/agent/sessions (metadata only). */
export const HUB_METHOD_LIST_HISTORY = "list_history";
/** Attach this browser to an agent; omit agentId to attach to the most recent one. */
export const HUB_METHOD_ATTACH = "attach";
/** Detach from the current agent. */
export const HUB_METHOD_DETACH = "detach";

export const HUB_METHODS = new Set([
  HUB_METHOD_LIST_SESSIONS,
  HUB_METHOD_LIST_HISTORY,
  HUB_METHOD_ATTACH,
  HUB_METHOD_DETACH,
  "health",
]);

// ═══════════════════════════════════════
// Hub-level events (hub → browser)
// ═══════════════════════════════════════

/** Live agent list changed (connect, disconnect, session_update). */
export const HUB_EVENT_SESSIONS = "hub:sessions";
/** The attached agent went away. */
export const HUB_EVENT_AGENT_GONE = "hub:agent_gone";

export type HistorySessionInfo = {
  sessionId: string | null;
  sessionName: string | null;
  sessionFile: string;
  cwd: string | null;
  mtime: number;
};
